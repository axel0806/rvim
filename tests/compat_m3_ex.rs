//! Ex commands checked against real Vim: ranges, line commands, `:s`,
//! `:g` and `:normal`.

mod common;
use common::{check, cross};

const TEXTS: &[&str] = &[
    "foo bar baz\nqux foo quux\n\n  indented foo line\nlast foo",
    "if (a[i] == b) {\n\treturn \"x(y)\";\n}\nend foofoo",
    "One. Two three!  Four?\nFive six.\n\nSeven eight.\nfoo-bar foo_bar",
    "aaaa aa\nabab abab\nxyz\n\tz foo",
];

