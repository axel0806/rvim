#[test]
fn search_with_operators() {
    let keys = [
        "d/foo<CR>",
        "d/foo/e<CR>",
        "d/foo/+1<CR>",
        "d?foo<CR>",
        "Gd?foo<CR>",
        "c/foo<CR>X<Esc>",
        "y/foo<CR>P",
        "y/foo/e<CR>P",
        "/foo<CR>dn",
        "/foo<CR>dN",
        "d/$<CR>",
        "d/^<CR>",
        "jd/^<CR>",
        "wd/\\n<CR>",
        "d/foo<CR>.",
        "d2/foo<CR>",
        "2d/foo<CR>",
        "d/nomatch<CR>",
        "d/foo<BS><BS><BS><BS>",
        "gU/foo<CR>",
        "g?/foo<CR>",
        ">/foo<CR>",
        "v/foo<CR>d",
        "v/foo/e<CR>d",
        "V/foo<CR>d",
        "<C-v>/foo<CR>d",
        "v?foo<CR>d",
        "wv/foo<CR>y",
        "dv/foo<CR>",
        "dV/foo<CR>",
        "d/foo<CR>u",
        "d*",
        "d#",
        "y*P",
        "c*X<Esc>",
    ];
    check(&cross(TEXTS, &keys));
}

